/**
 * Generates the nftables ruleset owned by this application.
 *
 * The output only ever touches `table inet cockpit_fw` and
 * `table ip cockpit_fw_nat`. It starts with the declare-then-delete idiom so
 * that `nft -f` atomically replaces both tables and nothing else.
 */

import {
    ANY_SERVICE,
    Endpoint,
    FirewallConfiguration,
    INET_TABLE_NAME,
    MANAGEMENT_TCP_PORTS,
    NAT_TABLE_NAME,
    PortSpecification,
    Verdict,
    allServices,
    describeEndpoint,
} from './model.js';
import { ParsedAddress, parseAddress, validateConfiguration } from './validation.js';

export const RULESET_HEADER = "# Generated by cockpit-firewall. Manual changes are overwritten.";

export interface GeneratedRuleset {
    text: string;
    /** Non-fatal issues, e.g. rules that match nothing because of address family mismatch. */
    warnings: string[];
}

export class ConfigurationError extends Error {
    readonly problems: string[];

    constructor(problems: string[]) {
        super(problems.join("\n"));
        this.name = "ConfigurationError";
        this.problems = problems;
    }
}

/** A list of alternative match fragments; a rule is emitted for every combination. */
type MatchAlternatives = string[][];

const NO_MATCH: MatchAlternatives = [[]];

/** Quotes a validated interface name. Validation guarantees no quotes or backslashes. */
function quoteInterface(name: string): string {
    return `"${name}"`;
}

function interfaceAlternatives(keyword: "iifname" | "oifname", interfaces: string[]): MatchAlternatives {
    if (interfaces.length === 1)
        return [[`${keyword} ${quoteInterface(interfaces[0])}`]];
    // Wildcards inside anonymous sets need recent nftables; expand them instead.
    if (interfaces.some(name => name.endsWith("*")))
        return interfaces.map(name => [`${keyword} ${quoteInterface(name)}`]);
    return [[`${keyword} { ${interfaces.map(quoteInterface).join(", ")} }`]];
}

function valueOrSet(values: string[]): string {
    return values.length === 1 ? values[0] : `{ ${values.join(", ")} }`;
}

function combine(...dimensions: MatchAlternatives[]): MatchAlternatives {
    return dimensions.reduce<MatchAlternatives>(
        (accumulated, dimension) => accumulated.flatMap(prefix => dimension.map(fragment => [...prefix, ...fragment])),
        NO_MATCH);
}

class RulesetBuilder {
    readonly warnings: string[] = [];
    private readonly configuration: FirewallConfiguration;

    constructor(configuration: FirewallConfiguration) {
        this.configuration = configuration;
    }

    private zoneInterfaces(zoneName: string): string[] {
        const zone = this.configuration.zones.find(candidate => candidate.name === zoneName);
        return zone ? zone.interfaces : [];
    }

    private hostAddresses(hostName: string | undefined): ParsedAddress[] | null {
        if (hostName === undefined)
            return null;
        const host = this.configuration.hosts.find(candidate => candidate.name === hostName);
        const unique = new Map<string, ParsedAddress>();
        for (const address of host ? host.addresses : []) {
            const parsed = parseAddress(address);
            if (parsed)
                unique.set(parsed.text, parsed);
        }
        return [...unique.values()];
    }

    private addressAlternatives(source: ParsedAddress[] | null, destination: ParsedAddress[] | null): MatchAlternatives {
        if (source === null && destination === null)
            return NO_MATCH;
        const alternatives: MatchAlternatives = [];
        for (const [family, keyword] of [["ipv4", "ip"], ["ipv6", "ip6"]] as const) {
            const sourceOfFamily = source?.filter(address => address.family === family).map(address => address.text);
            const destinationOfFamily = destination?.filter(address => address.family === family).map(address => address.text);
            if ((sourceOfFamily && sourceOfFamily.length === 0) || (destinationOfFamily && destinationOfFamily.length === 0))
                continue;
            const fragments: string[] = [];
            if (sourceOfFamily)
                fragments.push(`${keyword} saddr ${valueOrSet(sourceOfFamily)}`);
            if (destinationOfFamily)
                fragments.push(`${keyword} daddr ${valueOrSet(destinationOfFamily)}`);
            alternatives.push(fragments);
        }
        return alternatives;
    }

    private serviceAlternatives(serviceName: string): MatchAlternatives {
        if (serviceName === ANY_SERVICE)
            return NO_MATCH;
        const service = allServices(this.configuration).find(candidate => candidate.name === serviceName);
        const ports: PortSpecification[] = service ? service.ports : [];
        const alternatives: MatchAlternatives = [];
        for (const protocol of ["tcp", "udp"] as const) {
            const protocolPorts = ports.filter(port => port.protocol === protocol).map(port => String(port.port));
            if (protocolPorts.length > 0)
                alternatives.push([`${protocol} dport ${valueOrSet([...new Set(protocolPorts)])}`]);
        }
        return alternatives;
    }

    private endpointInterfaces(keyword: "iifname" | "oifname", endpoint: Endpoint): MatchAlternatives {
        return endpoint.zone === undefined ? NO_MATCH : interfaceAlternatives(keyword, this.zoneInterfaces(endpoint.zone));
    }

    private emit(lines: string[], alternatives: MatchAlternatives, verdict: string, label: string): void {
        if (alternatives.length === 0) {
            this.warnings.push(`${label} matches nothing (no common address family) and was skipped`);
            return;
        }
        for (const fragments of alternatives)
            lines.push([...fragments, "counter", verdict].join(" "));
    }

    forwardChainBody(): string[] {
        const lines: string[] = [];
        this.configuration.forwardRules.forEach((rule, index) => {
            if (!rule.enabled)
                return;
            const alternatives = combine(
                this.endpointInterfaces("iifname", rule.from),
                this.endpointInterfaces("oifname", rule.to),
                this.addressAlternatives(this.hostAddresses(rule.from.host), this.hostAddresses(rule.to.host)),
                this.serviceAlternatives(rule.service));
            this.emit(lines, alternatives, rule.action,
                      `Forward rule ${index + 1} (${describeEndpoint(rule.from)} -> ${describeEndpoint(rule.to)})`);
        });
        lines.push(...this.zonePolicyLines("forwardPolicy"));
        return lines;
    }

    inputChainBody(): string[] {
        const lines: string[] = [
            "iifname \"lo\" accept",
            "meta l4proto { icmp, ipv6-icmp } accept",
            "udp sport 67 udp dport 68 accept",
            "udp dport 546 accept",
        ];
        if (this.configuration.allowManagementAccess)
            lines.push(`tcp dport ${valueOrSet(MANAGEMENT_TCP_PORTS.map(String))} accept`);
        const listenPorts = [...new Set(this.configuration.wireguardListenPorts)].map(String);
        if (listenPorts.length > 0)
            lines.push(`udp dport ${valueOrSet(listenPorts)} accept`);
        this.configuration.inputRules.forEach((rule, index) => {
            if (!rule.enabled)
                return;
            const alternatives = combine(
                this.endpointInterfaces("iifname", rule.from),
                this.addressAlternatives(this.hostAddresses(rule.from.host), null),
                this.serviceAlternatives(rule.service));
            this.emit(lines, alternatives, rule.action, `Input rule ${index + 1} (${describeEndpoint(rule.from)})`);
        });
        lines.push(...this.zonePolicyLines("inputPolicy"));
        return lines;
    }

    private zonePolicyLines(policy: "forwardPolicy" | "inputPolicy"): string[] {
        const lines: string[] = [];
        for (const zone of this.configuration.zones)
            if (zone[policy] === "drop")
                for (const fragments of interfaceAlternatives("iifname", zone.interfaces))
                    lines.push([...fragments, "counter", "drop"].join(" "));
        return lines;
    }

    postroutingChainBody(): string[] {
        const lines: string[] = [];
        this.configuration.natRules.forEach((rule, index) => {
            if (!rule.enabled)
                return;
            let sourceAddresses: string[] | null = null;
            if (rule.sourceAddress !== undefined) {
                const host = this.configuration.hosts.find(candidate => candidate.name === rule.sourceAddress);
                sourceAddresses = (host ? host.addresses : [rule.sourceAddress])
                        .map(address => parseAddress(address)?.text ?? "");
            }
            const alternatives = combine(
                rule.sourceZone === undefined ? NO_MATCH : interfaceAlternatives("iifname", this.zoneInterfaces(rule.sourceZone)),
                sourceAddresses === null ? NO_MATCH : [[`ip saddr ${valueOrSet([...new Set(sourceAddresses)])}`]],
                interfaceAlternatives("oifname", this.zoneInterfaces(rule.egressZone)));
            this.emit(lines, alternatives, "masquerade", `NAT rule ${index + 1}`);
        });
        return lines;
    }
}

function chain(name: string, hookLine: string, preamble: string[], body: string[]): string[] {
    return [
        `\tchain ${name} {`,
        `\t\t${hookLine}`,
        ...[...preamble, ...body].map(line => `\t\t${line}`),
        "\t}",
    ];
}

/** @returns whether the configuration needs an input chain at all. */
function needsInputChain(configuration: FirewallConfiguration): boolean {
    return configuration.inputRules.some(rule => rule.enabled) ||
        configuration.zones.some(zone => zone.inputPolicy === "drop");
}

/**
 * Generates the complete nftables file for the configuration.
 * @throws ConfigurationError when the configuration is invalid.
 */
export function generateRuleset(configuration: FirewallConfiguration): GeneratedRuleset {
    const problems = validateConfiguration(configuration);
    if (problems.length > 0)
        throw new ConfigurationError(problems);

    const builder = new RulesetBuilder(configuration);
    const established = "ct state established,related accept";
    const policyAccept = (hook: string) => `type filter hook ${hook} priority filter; policy accept;`;

    const filterChains: string[] = [];
    const forwardBody = builder.forwardChainBody();
    if (forwardBody.length > 0)
        filterChains.push(...chain("forward", policyAccept("forward"), [established], forwardBody));
    if (needsInputChain(configuration)) {
        if (filterChains.length > 0)
            filterChains.push("");
        filterChains.push(...chain("input", policyAccept("input"), [established], builder.inputChainBody()));
    }

    const lines = [
        "#!/usr/sbin/nft -f",
        RULESET_HEADER,
        "",
        `table inet ${INET_TABLE_NAME}`,
        `delete table inet ${INET_TABLE_NAME}`,
        `table ip ${NAT_TABLE_NAME}`,
        `delete table ip ${NAT_TABLE_NAME}`,
        "",
        `table inet ${INET_TABLE_NAME} {`,
        ...filterChains,
        "}",
    ];

    const postroutingBody = builder.postroutingChainBody();
    if (postroutingBody.length > 0)
        lines.push(
            "",
            `table ip ${NAT_TABLE_NAME} {`,
            ...chain("postrouting", "type nat hook postrouting priority srcnat; policy accept;", [], postroutingBody),
            "}");

    return { text: lines.join("\n") + "\n", warnings: builder.warnings };
}

/** @returns the UI label for a verdict. */
export function describeVerdict(verdict: Verdict): string {
    return verdict === "accept" ? "Allow" : "Deny";
}
