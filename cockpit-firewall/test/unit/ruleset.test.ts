import assert from "node:assert/strict";
import { describe, test } from "node:test";

import { FirewallConfiguration, createEmptyConfiguration } from "../../src/model.ts";
import { ConfigurationError, generateRuleset } from "../../src/ruleset.ts";
import { parseWireguardConfiguration } from "../../src/wireguard-import.ts";

const WG0_CONFIGURATION = `[Interface]
Address = 10.99.0.1/24
ListenPort = 51820
PrivateKey = cHJpdmF0ZWtleXByaXZhdGVrZXlwcml2YXRla2V5MDA=

[Peer]
# Name = vpn-laptop
PublicKey = cHVibGlja2V5cHVibGlja2V5cHVibGlja2V5cHViMDE=
AllowedIPs = 10.99.0.3/32
`;

/** Acceptance scenario: VPN client vpn-laptop may reach only lan-server on tcp/22. */
function scenarioConfiguration(): FirewallConfiguration {
    const imported = parseWireguardConfiguration("wg0", WG0_CONFIGURATION);
    return {
        ...createEmptyConfiguration(),
        zones: [
            { name: "vpn", interfaces: ["wg0"], forwardPolicy: "drop", inputPolicy: "accept" },
            { name: "lan", interfaces: ["eth0"], forwardPolicy: "accept", inputPolicy: "accept" },
        ],
        hosts: [
            ...imported.hosts,
            { name: "lan-server", addresses: ["192.168.1.20"], origin: "manual" },
        ],
        forwardRules: [
            { from: { zone: "vpn", host: "vpn-laptop" }, to: { host: "lan-server" }, service: "ssh", action: "accept", enabled: true },
        ],
        natRules: [
            { sourceAddress: "10.99.0.0/24", egressZone: "lan", enabled: true },
        ],
    };
}

/** Reduces a ruleset to the one-line form used in the documentation (no counters, no header). */
function normalize(text: string): string {
    const body = text.split("\n")
            .map(line => line.trim())
            .filter(line => line && !line.startsWith("#") && !/^(table|delete table) \S+ \S+$/.test(line));
    return body.join("; ")
            .replace(/ counter/g, "")
            .replace(/\{; /g, "{ ")
            .replace(/; \}/g, " }")
            .replace(/;;/g, ";")
            .replace(/\} *; table/g, "}\ntable");
}

describe("acceptance scenario", () => {
    test("generates the expected ruleset", () => {
        const { text, warnings } = generateRuleset(scenarioConfiguration());
        assert.deepEqual(warnings, []);
        assert.equal(text, [
            "#!/usr/sbin/nft -f",
            "# Generated by cockpit-firewall. Manual changes are overwritten.",
            "",
            "table inet cockpit_fw",
            "delete table inet cockpit_fw",
            "table ip cockpit_fw_nat",
            "delete table ip cockpit_fw_nat",
            "",
            "table inet cockpit_fw {",
            "\tchain forward {",
            "\t\ttype filter hook forward priority filter; policy accept;",
            "\t\tct state established,related accept",
            "\t\tiifname \"wg0\" ip saddr 10.99.0.3 ip daddr 192.168.1.20 tcp dport 22 counter accept",
            "\t\tiifname \"wg0\" counter drop",
            "\t}",
            "}",
            "",
            "table ip cockpit_fw_nat {",
            "\tchain postrouting {",
            "\t\ttype nat hook postrouting priority srcnat; policy accept;",
            "\t\tip saddr 10.99.0.0/24 oifname \"eth0\" counter masquerade",
            "\t}",
            "}",
            "",
        ].join("\n"));
    });

    test("is equivalent to the documented one-line ruleset", () => {
        assert.equal(normalize(generateRuleset(scenarioConfiguration()).text), [
            'table inet cockpit_fw { chain forward { type filter hook forward priority filter; policy accept; ct state established,related accept; iifname "wg0" ip saddr 10.99.0.3 ip daddr 192.168.1.20 tcp dport 22 accept; iifname "wg0" drop } }',
            'table ip cockpit_fw_nat { chain postrouting { type nat hook postrouting priority srcnat; policy accept; ip saddr 10.99.0.0/24 oifname "eth0" masquerade } }',
        ].join("\n"));
    });
});

describe("only own tables", () => {
    const configurations: [string, FirewallConfiguration][] = [
        ["empty", createEmptyConfiguration()],
        ["scenario", scenarioConfiguration()],
        ["with input rules", { ...scenarioConfiguration(), inputRules: [{ from: { zone: "lan" }, service: "https", action: "accept", enabled: true }] }],
    ];
    for (const [label, configuration] of configurations)
        test(label, () => {
            const { text } = generateRuleset(configuration);
            const tableReferences = [...text.matchAll(/^\s*(?:delete |flush )?table (\S+) (\S+)/gm)].map(match => `${match[1]} ${match[2]}`);
            assert.ok(tableReferences.length >= 3);
            for (const reference of tableReferences)
                assert.ok(reference === "inet cockpit_fw" || reference === "ip cockpit_fw_nat", reference);
            assert.doesNotMatch(text, /flush ruleset|^\s*flush table/m);
            assert.match(text, /^table inet cockpit_fw\ndelete table inet cockpit_fw\ntable ip cockpit_fw_nat\ndelete table ip cockpit_fw_nat$/m);
        });

    test("empty configuration removes the NAT table and leaves an empty filter table", () => {
        const { text } = generateRuleset(createEmptyConfiguration());
        assert.doesNotMatch(text, /cockpit_fw_nat \{/);
        assert.match(text, /table inet cockpit_fw \{\n\}/);
    });
});

describe("rule generation", () => {
    test("input chain keeps management access and WireGuard listen ports before user rules", () => {
        const configuration = scenarioConfiguration();
        configuration.zones[1].inputPolicy = "drop";
        configuration.wireguardListenPorts = [51820];
        configuration.inputRules = [{ from: { zone: "lan" }, service: "ssh", action: "drop", enabled: true }];
        const { text } = generateRuleset(configuration);
        const input = text.slice(text.indexOf("chain input"));
        const managementIndex = input.indexOf("tcp dport { 22, 9090 } accept");
        assert.ok(managementIndex > 0);
        assert.ok(input.indexOf("udp dport 51820 accept") > managementIndex);
        assert.ok(input.indexOf("iifname \"eth0\" tcp dport 22 counter drop") > managementIndex);
        assert.ok(input.indexOf("iifname \"eth0\" counter drop") > input.indexOf("tcp dport 22 counter drop"));
    });

    test("input chain without management access omits the SSH/Cockpit accept", () => {
        const configuration = scenarioConfiguration();
        configuration.zones[1].inputPolicy = "drop";
        configuration.allowManagementAccess = false;
        assert.doesNotMatch(generateRuleset(configuration).text, /9090/);
    });

    test("no input chain unless input rules or input drop policies exist", () => {
        assert.doesNotMatch(generateRuleset(scenarioConfiguration()).text, /chain input/);
    });

    test("mixed families split per family and multi-protocol services split per protocol", () => {
        const configuration = scenarioConfiguration();
        configuration.hosts.push({ name: "dual", addresses: ["192.168.1.10", "fd00::10"], origin: "manual" });
        configuration.forwardRules = [{ from: { zone: "lan" }, to: { zone: "vpn", host: "dual" }, service: "dns", action: "accept", enabled: true }];
        const { text } = generateRuleset(configuration);
        assert.match(text, /iifname "eth0" oifname "wg0" ip daddr 192\.168\.1\.10 tcp dport 53 counter accept/);
        assert.match(text, /iifname "eth0" oifname "wg0" ip daddr 192\.168\.1\.10 udp dport 53 counter accept/);
        assert.match(text, /iifname "eth0" oifname "wg0" ip6 daddr fd00::10 tcp dport 53 counter accept/);
    });

    test("family mismatch is skipped with a warning", () => {
        const configuration = scenarioConfiguration();
        configuration.hosts.push({ name: "only6", addresses: ["fd00::1"], origin: "manual" });
        configuration.forwardRules.push({ from: { host: "vpn-laptop" }, to: { host: "only6" }, service: "any", action: "accept", enabled: true });
        const { warnings } = generateRuleset(configuration);
        assert.equal(warnings.length, 1);
    });

    test("disabled rules are not generated", () => {
        const configuration = scenarioConfiguration();
        configuration.forwardRules[0].enabled = false;
        assert.doesNotMatch(generateRuleset(configuration).text, /192\.168\.1\.198/);
    });

    test("multiple interfaces use a set, wildcards are expanded", () => {
        const configuration = scenarioConfiguration();
        configuration.zones[0].interfaces = ["wg0", "wg1"];
        assert.match(generateRuleset(configuration).text, /iifname \{ "wg0", "wg1" \} counter drop/);
        configuration.zones[0].interfaces = ["wg0", "tun*"];
        const { text } = generateRuleset(configuration);
        assert.match(text, /iifname "wg0" counter drop/);
        assert.match(text, /iifname "tun\*" counter drop/);
    });
});

describe("rejects unsafe input", () => {
    const injections = [
        'wg0" accept; flush ruleset; #',
        "wg0\nflush ruleset",
        "eth0 }",
        "$(reboot)",
        "a/b",
        "verylonginterface0",
        "",
    ];
    for (const interfaceName of injections)
        test(`interface ${JSON.stringify(interfaceName)}`, () => {
            const configuration = scenarioConfiguration();
            configuration.zones[0].interfaces = [interfaceName];
            assert.throws(() => generateRuleset(configuration), ConfigurationError);
        });

    for (const address of ["10.99.0.3; flush ruleset", "10.99.0.3/24", "300.1.1.1", "10.0.0.1/33", "fd00::1::2", "1.2.3.4 }", "fe80::1%eth0"])
        test(`address ${JSON.stringify(address)}`, () => {
            const configuration = scenarioConfiguration();
            configuration.hosts[1].addresses = [address];
            assert.throws(() => generateRuleset(configuration), ConfigurationError);
        });

    for (const name of ['lan-server"', "lan server", "1host", "host;drop", "a".repeat(64)])
        test(`host name ${JSON.stringify(name)}`, () => {
            const configuration = scenarioConfiguration();
            configuration.hosts[1].name = name;
            configuration.forwardRules[0].to = { host: name };
            assert.throws(() => generateRuleset(configuration), ConfigurationError);
        });

    for (const port of ["0", "65536", "22;", "22 accept", "100-10", "22-22", "01"])
        test(`service port ${JSON.stringify(port)}`, () => {
            const configuration = scenarioConfiguration();
            configuration.services = [{ name: "custom", ports: [{ protocol: "tcp", port }] }];
            assert.throws(() => generateRuleset(configuration), ConfigurationError);
        });

    test("unknown references", () => {
        const configuration = scenarioConfiguration();
        configuration.forwardRules[0].service = "telnet";
        configuration.forwardRules[0].from.zone = "dmz";
        const error = (() => {
            try {
                generateRuleset(configuration);
            } catch (caught) {
                return caught as ConfigurationError;
            }
            return null;
        })();
        assert.ok(error);
        assert.equal(error.problems.length, 2);
    });

    test("NAT source must be IPv4", () => {
        const configuration = scenarioConfiguration();
        configuration.natRules[0].sourceAddress = "fd00::/64";
        assert.throws(() => generateRuleset(configuration), ConfigurationError);
    });

    test("invalid verdict", () => {
        const configuration = scenarioConfiguration();
        (configuration.forwardRules[0] as { action: string }).action = "accept; flush ruleset";
        assert.throws(() => generateRuleset(configuration), ConfigurationError);
    });
});
